let i = 100 // Starting point
while (i >=0) {// assignment specifies to end at 0, so we will loop until i is greater than or >equal< to 0
    console.log(i);// This will print the current value of i to the console each time the loop runs
    alert(i);// This will show the current value of i in an alert box each time the loop runs
    i -= 10
}// This way we will get the numbers from 100 to 0, decreasing by 10 each time.